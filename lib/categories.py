def _norm(s: str) -> str:
    """Normalise a category string for matching: lowercase, drop packaging
    qualifiers, collapse punctuation (including parentheses) to single spaces."""
    s = (s or "").lower()
    s = re.sub(r"[^a-z0-9]+", " ", s)  # punctuation (incl. parens) -> space
    s = re.sub(r"\b(smd|smt|tht)\b", " ", s)  # drop packaging tokens
    return " ".join(s.split())


# normalised LCSC name -> final category
_NORM_MAP = {}
for _final, _names in SOURCES.items():
    for _n in _names:
        _NORM_MAP[_norm(_n)] = _final
# final names are themselves valid inputs (idempotent resolution)
for _final in FINAL_CATEGORIES:
    _NORM_MAP.setdefault(_norm(_final), _final)

_FINAL_NORMS = [(f, _norm(f)) for f in FINAL_CATEGORIES]


def resolve_category(raw: str, cutoff: float = 0.62) -> str:
    """Map an arbitrary LCSC category string onto one final category.

    Exact normalised match first, then closest match (difflib) against known
    LCSC names and final names, then ``Uncategorized``.
    """
    n = _norm(raw)
    if not n:
        return "Uncategorized"
    if n in _NORM_MAP:
        return _NORM_MAP[n]

    best, best_r = "Uncategorized", 0.0
    for key, final in _NORM_MAP.items():
        r = SequenceMatcher(None, n, key).ratio()
        if r > best_r:
            best_r, best = r, final
    for final, fnorm in _FINAL_NORMS:
        r = SequenceMatcher(None, n, fnorm).ratio()
        if r > best_r:
            best_r, best = r, final

    if best_r >= cutoff:
        return best
    return "Uncategorized"
