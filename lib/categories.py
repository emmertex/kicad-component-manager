"""Fixed KiCad category taxonomy and LCSC -> final-category resolution.

LCSC exposes ~600 leaf categories. For PCB/KiCad use most of that detail is
noise, so we collapse it into a small fixed set of final categories
(``FINAL_CATEGORIES``). Each final category becomes exactly one KiCad symbol
library, and the set never changes at runtime — so the libraries (and the
sym-lib-table) can be created up front and KiCad never needs a restart when a
new part in a new category arrives.

``resolve_category`` maps any incoming LCSC category string onto one final
category:
  1. exact match against the hand-built ``SOURCES`` mapping (normalised),
  2. otherwise the closest match (difflib) against the known LCSC names and the
     final names, if it clears a similarity threshold,
  3. otherwise ``Uncategorized``.

Step 2 is what lets unseen variants resolve sensibly, e.g.
``"Photodiodes - SMD"`` -> the bucket that owns ``"Photodiodes"``.
"""

